"""Compare every re-run validation result with the original (backed up before the re-run) and state which paper numbers are reproduced.
Originals: C:\\bbbrep\\backup_prerun_*\\results  (and *_prev.csv for the two docking files moved aside); re-runs: results/.
A number counts as reproduced when it agrees within the tolerance given for it. Output: results/REAUDIT_COMPARISON.txt   Run with bbbenv python from the project root."""
import glob, os
import numpy as np, pandas as pd

BK = sorted(glob.glob("C:/bbbrep/backup_prerun_*"))[-1] + "/results/"
L = []


def log(s):
    L.append(s); print(s)


def load(name, new=True):
    return pd.read_csv(("results/%s.csv" if new else BK + "%s.csv") % name)


def compare_numeric(name, tol, key=None):
    try:
        a, b = load(name, False), load(name, True)
    except Exception as e:
        log("%-44s not comparable: %s" % (name, str(e)[:60])); return
    if a.shape != b.shape:
        log("%-44s shape differs: old %s new %s" % (name, a.shape, b.shape)); return
    num = [c for c in a.columns if pd.api.types.is_numeric_dtype(a[c]) and c in b.columns]
    d = max(float(np.nanmax(np.abs(a[c].values.astype(float) - b[c].values.astype(float)))) if len(a) else 0.0 for c in num)
    log("%-44s max |old - new| over %d numeric columns = %.4f  (tolerance %.3f) -> %s" % (name, len(num), d, tol, "REPRODUCED" if d <= tol else "DIFFERS"))


compare_numeric("AD_ACHE_BASELINES", 0.01)
compare_numeric("AD_BBB_BASELINES", 0.01)
compare_numeric("AD_EXPOSURE_LOGBB_VALIDATION", 0.01)
compare_numeric("AD_PGP_GATE_VALIDATION", 0.01)
compare_numeric("AD_RANDOM_VS_SCAFFOLD", 0.02)
compare_numeric("AD_SPLIT_DETERMINISTIC_SAME_MODELS", 0.02)
# matched-pair ablation: arm means
try:
    a, b = load("AD_MMP_ABLATION", False), load("AD_MMP_ABLATION", True)
    ma, mb = a.groupby("arm").d_audit.mean(), b.groupby("arm").d_audit.mean()
    for arm in ma.index:
        log("MMP ablation arm %-34s old %.3f new %.3f -> %s" % (arm, ma[arm], mb.get(arm, np.nan), "REPRODUCED" if abs(ma[arm] - mb.get(arm, np.nan)) <= 0.005 else "DIFFERS"))
except Exception as e:
    log("MMP ablation not comparable: " + str(e)[:80])
# paired oracle: number of repeats in which the consensus top-k beats in-loop top-k
try:
    a, b = load("AD_PAIRED_ORACLE_VALUE", False), load("AD_PAIRED_ORACLE_VALUE", True)
    for ds in a.dataset.unique():
        wa = int((a[a.dataset == ds]["prec topk min(in,aud)"] > a[a.dataset == ds]["prec topk in-loop"]).sum()); wb = int((b[b.dataset == ds]["prec topk min(in,aud)"] > b[b.dataset == ds]["prec topk in-loop"]).sum())
        log("Second-model agreement, %-18s consensus better in old %d / new %d of 20 repeats -> %s" % (ds, wa, wb, "REPRODUCED" if wa == wb else "DIFFERS"))
except Exception as e:
    log("paired oracle not comparable: " + str(e)[:80])
# redocking
try:
    a = pd.read_csv("results/AD_REDOCK_RMSD_prev.csv"); b = pd.read_csv("results/AD_REDOCK_RMSD.csv")
    log("Redocking donepezil: old RMSD %.3f-%.3f over %d runs | new %.3f-%.3f over %d runs | all <= 2.0 A (new): %s -> %s" % (a.rmsd_top.min(), a.rmsd_top.max(), len(a), b.rmsd_top.min(), b.rmsd_top.max(), len(b), bool((b.rmsd_top <= 2).all()),
        "REPRODUCED" if abs(a.rmsd_top.max() - b.rmsd_top.max()) < 0.05 and abs(a.rmsd_top.min() - b.rmsd_top.min()) < 0.05 else "DIFFERS"))
except Exception as e:
    log("redocking not comparable: " + str(e)[:80])
# docking enrichment (summary file regenerated by ad_dock_enrichment_matched_summary.py)
try:
    a = pd.read_csv(BK + "AD_DOCK_ENRICHMENT_MATCHED_SUMMARY.csv"); b = pd.read_csv("results/AD_DOCK_ENRICHMENT_MATCHED_SUMMARY.csv")
    for (ra, rb) in zip(a.itertuples(), b.itertuples()):
        log("Docking enrichment, %-52s Vina AUC old %.3f new %.3f | properties-only old %.3f new %.3f -> %s" % (ra.set[:52], ra.vina_auc, rb.vina_auc, ra.property_only_auc_logistic, rb.property_only_auc_logistic, "REPRODUCED" if abs(ra.vina_auc - rb.vina_auc) <= 0.03 else "DIFFERS"))
except Exception as e:
    log("docking enrichment not comparable: " + str(e)[:80])
# independent re-implementations
if os.path.exists("results/AD_V2_INDEPENDENT_CHECKS.txt"):
    log("\nIndependent re-implementations:\n" + open("results/AD_V2_INDEPENDENT_CHECKS.txt").read())
open("results/REAUDIT_COMPARISON.txt", "w").write("\n".join(L))
